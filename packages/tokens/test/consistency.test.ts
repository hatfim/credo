import { readFileSync } from "node:fs";
import { beforeAll, describe, expect, it } from "vitest";
import { buildArtifacts, type Artifacts, type TokenTable } from "../src/build";
import { checkConsistency } from "../src/consistency";
import { updateContractDoc } from "../src/contract";
import type { TokenFile } from "../src/model";
import { makeValid } from "./fixtures/valid";

const DOC = "<!-- roles:start (generated by `credo-tokens contract`, do not edit) -->\n<!-- roles:end -->\n";

describe("consistency (fixture)", () => {
  let file: TokenFile;
  let art: Artifacts;
  let doc: string;
  beforeAll(async () => {
    file = makeValid();
    art = await buildArtifacts(file);
    doc = updateContractDoc(DOC, file);
  });

  it("passes when everything derives from the same file", () => {
    expect(checkConsistency(art, file, doc)).toEqual([]);
  });

  it("fails when a CSS value diverges", () => {
    const css = art.css.replace("--cr-surface-page: #fafafa;", "--cr-surface-page: #fafafb;");
    expect(checkConsistency({ ...art, css }, file, doc).map((i) => i.message)).toContainEqual(
      expect.stringContaining("CSS light value #fafafb differs"),
    );
  });

  it("fails when CSS lacks a role", () => {
    const css = art.css.replace(/ {2}--cr-border-default: [^;]+;\n/g, "");
    expect(checkConsistency({ ...art, css }, file, doc).length).toBeGreaterThan(0);
  });

  it("fails when a type is missing", () => {
    const types = art.types.replace('  | "border.default"\n', "");
    expect(checkConsistency({ ...art, types }, file, doc)).toContainEqual(
      expect.objectContaining({ code: "diverged", path: "border.default" }),
    );
  });

  it("fails when the docs table drifts from the file", () => {
    const table = JSON.parse(art.table) as TokenTable;
    table.roles = table.roles.filter((r) => r.path !== "content.primary");
    expect(checkConsistency({ ...art, table: JSON.stringify(table) }, file, doc)).toContainEqual(
      expect.objectContaining({ path: "content.primary" }),
    );
  });

  it("fails when the schema lacks a role", () => {
    const schema = JSON.parse(art.schema);
    delete schema.properties.border.properties.default;
    expect(checkConsistency({ ...art, schema: JSON.stringify(schema) }, file, doc).length).toBeGreaterThan(0);
  });

  it("fails when the contract document is stale", () => {
    const stale = doc.replace("`border.default`", "`border.defaults`");
    expect(checkConsistency(art, file, stale).map((i) => i.message)).toContainEqual(
      expect.stringContaining("out of date"),
    );
  });

  it("fails when the file gains a role the outputs do not know about", () => {
    const changed = makeValid();
    changed["Semantic/Light"].surface.extra = changed["Semantic/Light"].surface.page;
    changed["Semantic/Dark"].surface.extra = changed["Semantic/Dark"].surface.page;
    expect(checkConsistency(art, changed, doc).length).toBeGreaterThan(0);
  });
});

describe("consistency (real token file and contract document)", () => {
  it("CSS, types, schema, table and docs agree with the file", async () => {
    const file = JSON.parse(readFileSync(new URL("../generated/tokens.json", import.meta.url), "utf8")) as TokenFile;
    const doc = readFileSync(new URL("../../../docs/token-contract-v0.md", import.meta.url), "utf8");
    const art = await buildArtifacts(file);
    expect(checkConsistency(art, file, doc)).toEqual([]);
  });
});
