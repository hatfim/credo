import { ROLE_GROUPS } from "./constants";
import { cssVariable } from "./naming";
import { rolePaths, type TokenFile } from "./model";

export const ROLES_START = "<!-- roles:start (generated by `credo-tokens contract`, do not edit) -->";
export const ROLES_END = "<!-- roles:end -->";

/** The generated role list, grouped by contract group. */
export function renderRoleSection(file: TokenFile): string {
  const roles = rolePaths(file);
  const lines: string[] = [`${roles.length} roles in ${ROLE_GROUPS.length} groups, identical in light and dark.`, ""];
  for (const g of ROLE_GROUPS) {
    const rs = roles.filter((r) => r.split(".")[0] === g);
    lines.push(`#### \`${g}\` (${rs.length})`, "", "| Role | CSS variable | Tailwind colour name |", "| --- | --- | --- |");
    for (const r of rs) lines.push(`| \`${r}\` | \`${cssVariable(r)}\` | \`${r.replace(/\./g, "-")}\` |`);
    lines.push("");
  }
  return lines.join("\n").trimEnd();
}

/** Replace the marked block in the document, or throw if the markers are missing. */
export function updateContractDoc(doc: string, file: TokenFile): string {
  const a = doc.indexOf(ROLES_START);
  const b = doc.indexOf(ROLES_END);
  if (a === -1 || b === -1 || b < a) throw new Error(`Contract document is missing the ${ROLES_START} / ${ROLES_END} markers.`);
  return `${doc.slice(0, a)}${ROLES_START}\n\n${renderRoleSection(file)}\n\n${doc.slice(b)}`;
}
