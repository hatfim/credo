// @vitest-environment node
// Asserts on the production build (`next build`): prerendered HTML and the emitted stylesheet.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { beforeAll, describe, expect, it } from "vitest";

const root = path.resolve(import.meta.dirname, "..");
const htmlPath = path.join(root, ".next", "server", "app", "index.html");
const staticDir = path.join(root, ".next", "static");

function cssFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? cssFiles(path.join(dir, e.name)) : e.name.endsWith(".css") ? [path.join(dir, e.name)] : [],
  );
}

// Class names only Button uses, built from parts so Tailwind's source scan cannot find them in this file.
const fromButtonOnly = [["inline", "flex"].join("-"), ["bg", "actions", "secondary", "default"].join("-")] as const;

let html: string;
let css: string;

beforeAll(() => {
  if (!existsSync(htmlPath)) throw new Error(".next is missing: run `pnpm build` before `pnpm test`.");
  html = readFileSync(htmlPath, "utf8");
  css = cssFiles(staticDir).map((f) => readFileSync(f, "utf8")).join("\n");
});

describe("next consumer: production build", () => {
  it("prerenders the server component icon and both themed Button regions", () => {
    expect(html).toContain('data-testid="server-icon"');
    expect(html).toMatch(/<svg[^>]*data-testid="server-icon"/);
    expect(html).toContain('data-theme="light"');
    expect(html).toContain('data-theme="dark"');
    expect(html).toContain('data-slot="button"');
  });

  it("emits Credo utilities and both token theme blocks", () => {
    expect(css).toMatch(/\.bg-surface-page\s*\{[^}]*var\(--cr-surface-page\)/);
    expect(css).toMatch(/\.bg-actions-primary-default\s*\{[^}]*var\(--cr-actions-primary-default\)/);
    // Generated by scanning the installed @usecredo/ui, not by the app's own sources.
    expect(css).toMatch(new RegExp(`\\.${fromButtonOnly[0]}\\s*\\{`));
    expect(css).toMatch(new RegExp(`\\.${fromButtonOnly[1]}\\s*\\{[^}]*var\\(--cr-actions-secondary-default\\)`));
    expect(css).toMatch(/\[data-theme=["']?light["']?\]/);
    expect(css).toMatch(/\[data-theme=["']?dark["']?\]/);
  });

  it("imports the icon from the server entry, never the client entry, in the server page", () => {
    const page = readFileSync(path.join(root, "src", "app", "page.tsx"), "utf8");
    expect(page).toContain('from "@usecredo/icons/server"');
    expect(page).not.toMatch(/from "@usecredo\/icons"/);
    expect(page).not.toMatch(/^"use client"/m);
  });
});
